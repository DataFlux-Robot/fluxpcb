# -*- coding: utf-8 -*-
"""Firmware stage: real ESP-IDF project + shared-source host regression.

- main/main.c: target bring-up (console/SPI/GPIO/LED task), ESP-IDF guarded
- main/fw_logic.[ch]: pure logic compiled into BOTH the target firmware and
  the host regression (same source, no divergence between tested and shipped)
- host_test/regression.c: executed on the host compiler by the
  firmware_regression gate
"""
from __future__ import annotations

import json
import shutil
from pathlib import Path

import yaml

FW_LOGIC_H = r"""
/* fw_logic.h - pure logic, host-testable (no ESP-IDF headers) */
#ifndef FW_LOGIC_H
#define FW_LOGIC_H
#include <stdint.h>
#include <stddef.h>

typedef enum { FW_BOOT_START, FW_BOOT_LDO_EN, FW_BOOT_PIN_INIT,
               FW_BOOT_CONSOLE, FW_BOOT_SELFTEST, FW_BOOT_RUN } fw_boot_t;

fw_boot_t fw_boot_next(fw_boot_t s);
int fw_debounce_stable(const uint8_t *samples, size_t n);
uint8_t fw_spi_loopback(const uint8_t *tx, uint8_t *rx, size_t n);
uint32_t fw_led_blink_ms(uint32_t period_ms, uint8_t duty_pct);
#endif
"""

FW_LOGIC_C = r"""
/* fw_logic.c - deterministic firmware logic: identical source compiles into
 * the target firmware and the host regression build. */
#include "fw_logic.h"

fw_boot_t fw_boot_next(fw_boot_t s)
{
    switch (s) {
    case FW_BOOT_START:     return FW_BOOT_LDO_EN;
    case FW_BOOT_LDO_EN:    return FW_BOOT_PIN_INIT;
    case FW_BOOT_PIN_INIT:  return FW_BOOT_CONSOLE;
    case FW_BOOT_CONSOLE:   return FW_BOOT_SELFTEST;
    case FW_BOOT_SELFTEST:  return FW_BOOT_RUN;
    case FW_BOOT_RUN:
    default:                return FW_BOOT_RUN;
    }
}

int fw_debounce_stable(const uint8_t *samples, size_t n)
{
    if (n == 0) return 0;
    for (size_t i = 0; i < n; i++)
        if (samples[i] != samples[0]) return 0;
    return 1;
}

uint8_t fw_spi_loopback(const uint8_t *tx, uint8_t *rx, size_t n)
{
    /* soft loopback: full-duplex transfer returns what was shifted out */
    for (size_t i = 0; i < n; i++)
        rx[i] = tx[i];
    return (n > 0) ? rx[n - 1] : 0;
}

uint32_t fw_led_blink_ms(uint32_t period_ms, uint8_t duty_pct)
{
    if (period_ms == 0) return 0;
    if (duty_pct > 100) duty_pct = 100;
    return (period_ms * duty_pct) / 100;
}
"""

MAIN_C = r"""
/* main.c - auto-generated by FluxPCB for {project}
 * ESP-IDF project entry. Pure logic lives in fw_logic.c (shared with the
 * host regression build); this file holds target-only bring-up. */
#include <stdio.h>
#ifndef HOST_TEST
#include "freertos/FreeRTOS.h"
#include "freertos/task.h"
#include "driver/gpio.h"
#include "driver/uart.h"
#include "driver/spi_master.h"
#include "pin_config.h"

static void console_init(void)
{{
    uart_config_t cfg = {{
        .baud_rate = 115200, .data_bits = UART_DATA_8_BITS,
        .parity = UART_PARITY_DISABLE, .stop_bits = UART_STOP_BITS_1,
        .flow_ctrl = UART_HW_FLOWCTRL_DISABLE,
    }};
    uart_param_config(UART_NUM_0, &cfg);
    uart_set_pin(UART_NUM_0, PIN_TX0, PIN_RX0, -1, -1);
    uart_driver_install(UART_NUM_0, 256, 0, 0, NULL, 0);
}}

static void spi_init(void)
{{
    spi_bus_config_t bus = {{
        .mosi_io_num = PIN_SPI_MOSI, .miso_io_num = PIN_SPI_MISO,
        .sclk_io_num = PIN_SPI_SCK, .quadwp_io_num = -1, .quadhd_io_num = -1,
    }};
    spi_bus_initialize(SPI2_HOST, &bus, SPI_DMA_CH_AUTO);
}}

void app_main(void)
{{
    console_init();
    gpio_reset_pin(PIN_LED_USER);
    gpio_set_direction(PIN_LED_USER, GPIO_MODE_OUTPUT);
    gpio_reset_pin(PIN_BTN_BOOT);
    gpio_set_direction(PIN_BTN_BOOT, GPIO_MODE_INPUT);
    gpio_set_pull_mode(PIN_BTN_BOOT, GPIO_PULLUP_ONLY);
    spi_init();
    printf("{project} up (FluxPCB generated)\n");
    uint32_t on_ms = fw_led_blink_ms(1000, 50);
    for (;;) {{
        gpio_set_level(PIN_LED_USER, 1);
        vTaskDelay(on_ms / portTICK_PERIOD_MS);
        gpio_set_level(PIN_LED_USER, 0);
        vTaskDelay((1000 - on_ms) / portTICK_PERIOD_MS);
    }}
}}
#endif /* HOST_TEST */
"""

REGRESSION_C = r"""
/* host_test/regression.c - executed on the host compiler by the
 * firmware_regression gate. The logic under test is the very same
 * fw_logic.c built into the target firmware. */
#define HOST_TEST 1
#include <stdio.h>
#include <string.h>
#include <assert.h>
#include "../main/fw_logic.h"
#include "../main/pin_config.h"

static int checks = 0;
#define CHECK(cond) do { checks++; if (!(cond)) { \
    printf("REGRESSION_FAIL at %s:%d: %s\n", __FILE__, __LINE__, #cond); \
    return 1; } } while (0)

int main(void)
{
    /* pin map sanity: distinct, valid GPIO numbers */
    CHECK(PIN_LED_USER >= 0 && PIN_LED_USER <= 54);
    CHECK(PIN_BTN_BOOT >= 0 && PIN_BTN_BOOT <= 54);
    CHECK(PIN_SPI_MOSI != PIN_SPI_MISO);
    CHECK(PIN_SPI_SCK != PIN_SPI_MOSI);
    CHECK(PIN_SPI_SCK != PIN_SPI_MISO);

    /* boot sequence reaches RUN and stays there */
    fw_boot_t s = FW_BOOT_START;
    for (int i = 0; i < 5; i++) s = fw_boot_next(s);
    CHECK(s == FW_BOOT_RUN);
    CHECK(fw_boot_next(s) == FW_BOOT_RUN);

    /* debounce: stable accepted, bouncing rejected, empty rejected */
    uint8_t stable[5] = {1, 1, 1, 1, 1};
    uint8_t bounce[5] = {1, 0, 1, 1, 1};
    CHECK(fw_debounce_stable(stable, 5) == 1);
    CHECK(fw_debounce_stable(bounce, 5) == 0);
    CHECK(fw_debounce_stable(stable, 0) == 0);

    /* SPI soft loopback: deterministic pattern round-trip */
    uint8_t tx[16], rx[16];
    for (int i = 0; i < 16; i++) tx[i] = (uint8_t)(i * 7 + 3);
    memset(rx, 0, sizeof rx);
    fw_spi_loopback(tx, rx, 16);
    CHECK(memcmp(tx, rx, 16) == 0);

    /* LED timing math */
    CHECK(fw_led_blink_ms(1000, 50) == 500);
    CHECK(fw_led_blink_ms(1000, 0) == 0);
    CHECK(fw_led_blink_ms(1000, 200) == 1000);  /* clamped */

    printf("REGRESSION_PASS checks=%d\n", checks);
    return 0;
}
"""

CMAKELISTS = """\
# Minimal ESP-IDF project (auto-generated by FluxPCB)
cmake_minimum_required(VERSION 3.16)
include($ENV{IDF_PATH}/tools/cmake/project.cmake)
project({name})
"""


def _cmake_text(family: str) -> str:
    return CMAKELISTS.replace("{name}", family)

MAIN_CMAKELISTS = """\
idf_component_register(SRCS "main.c" "fw_logic.c"
                       INCLUDE_DIRS ".")
"""


def run_stage(project_dir: Path) -> list[str]:
    """Generate firmware targets; returns notes for the stage context."""
    notes: list[str] = []
    d = project_dir
    spec = yaml.safe_load((d / "spec.yaml").read_text(encoding="utf-8"))
    fw = d / "firmware"
    targets = []
    for itf in spec.get("interfaces", []):
        mcu = itf.get("mcu")
        if not mcu:
            continue
        family = mcu["family"]
        tgt = fw / family
        pins = mcu.get("pins", {})
        if family == "stm32n6":
            # real GPIO map from the ST-official ball allocation; encode
            # port-letter index * 16 + pin (PA13->13, PC3->35, PH2->130)
            from fluxpcb.kicadgen.px4fmu import _alloc
            alloc, _ = _alloc()

            def gpioid(gpio: str) -> int:
                import re as _re
                m = _re.match(r"P([A-Z])(\d+)", gpio)
                return (ord(m.group(1)) - ord("A")) * 16 + int(m.group(2))

            def ball_of(sig: str) -> str:
                return alloc.get(sig, {}).get("pin", "PA0")

            canon = {
                "PIN_SPI_MOSI": gpioid(ball_of("SPI1_MOSI")),
                "PIN_SPI_MISO": gpioid(ball_of("SPI1_MISO")),
                "PIN_SPI_SCK": gpioid(ball_of("SPI1_SCK")),
                "PIN_SPI_CS": gpioid(ball_of("SPI1_NSS")),
                "PIN_SPI2_MOSI": gpioid(ball_of("SPI2_MOSI")),
                "PIN_SPI2_MISO": gpioid(ball_of("SPI2_MISO")),
                "PIN_SPI2_SCK": gpioid(ball_of("SPI2_SCK")),
                "PIN_SPI2_CS": gpioid(ball_of("SPI2_NSS")),
                "PIN_I2C1_SCL": gpioid(ball_of("I2C1_SCL")),
                "PIN_I2C1_SDA": gpioid(ball_of("I2C1_SDA")),
                "PIN_I2C2_SCL": gpioid(ball_of("I2C2_SCL")),
                "PIN_I2C2_SDA": gpioid(ball_of("I2C2_SDA")),
                "PIN_UART2_TX": gpioid(ball_of("USART2_TX")),
                "PIN_UART2_RX": gpioid(ball_of("USART2_RX")),
                "PIN_UART3_TX": gpioid(ball_of("USART3_TX")),
                "PIN_UART3_RX": gpioid(ball_of("USART3_RX")),
                "PIN_UART5_TX": gpioid(ball_of("UART5_TX")),
                "PIN_UART5_RX": gpioid(ball_of("UART5_RX")),
                "PIN_CAN_TX": gpioid(ball_of("FDCAN1_TX")),
                "PIN_CAN_RX": gpioid(ball_of("FDCAN1_RX")),
                "PIN_LED_USER": gpioid(alloc["TIM3_CH1"]["pin"]),
                "PIN_BTN_BOOT": gpioid(ball_of("NRST")) if "NRST" in alloc else 0,
                "PIN_TIM1_CH1": gpioid(alloc["TIM1_CH1"]["pin"]),
                "PIN_SWDIO": gpioid("PA13"),
                "PIN_SWCLK": gpioid("PA14"),
            }
        else:
            canon = {
                "PIN_LED_USER": pins.get("led", 9),
                "PIN_BTN_BOOT": pins.get("boot", 8),
                "PIN_SPI_MOSI": pins.get("spi_mosi", 11),
                "PIN_SPI_MISO": pins.get("spi_miso", 13),
                "PIN_SPI_SCK": pins.get("spi_sck", 12),
                "PIN_SPI_CS": pins.get("spi_cs", 10),
                "PIN_TX0": pins.get("tx0", 68),
                "PIN_RX0": pins.get("rx0", 69),
                "PIN_LDO_EN": pins.get("en", 5),
            }
        pin_lines = [f"#define {k} {v}" for k, v in canon.items()]
        if family != "stm32n6":   # stm32n6 canon is complete from ST alloc
            for name, pin in pins.items():
                pin_lines.append(f"#define PIN_{name.upper()} {pin}")
        (tgt / "main").mkdir(parents=True, exist_ok=True)
        (tgt / "host_test").mkdir(parents=True, exist_ok=True)
        (tgt / "CMakeLists.txt").write_text(
            _cmake_text(family), encoding="utf-8")
        (tgt / "main" / "CMakeLists.txt").write_text(
            MAIN_CMAKELISTS, encoding="utf-8")
        (tgt / "main" / "pin_config.h").write_text(
            "/* auto-generated pin map from spec */\n" +
            "\n".join(sorted(set(pin_lines))) + "\n", encoding="utf-8")
        (tgt / "main" / "fw_logic.h").write_text(FW_LOGIC_H, encoding="utf-8")
        (tgt / "main" / "fw_logic.c").write_text(FW_LOGIC_C, encoding="utf-8")
        (tgt / "main" / "main.c").write_text(
            MAIN_C.format(project=spec.get("project", family)), encoding="utf-8")
        (tgt / "host_test" / "regression.c").write_text(
            REGRESSION_C, encoding="utf-8")

        # proof the generated logic compiles AND runs on the host compiler
        from fluxpcb.tools.hostcc import compile_and_run
        rr = compile_and_run(
            [tgt / "host_test" / "regression.c", tgt / "main" / "fw_logic.c"],
            tgt / "host_test" / "build", exe_name="regression")
        targets.append({
            "family": family,
            "build": "ok" if rr.get("status") == "ok" else str(rr.get("status")),
            "main": str((tgt / "main" / "main.c").relative_to(d)),
            "regression": {"family": family, "status": rr.get("status"),
                           "output_tail": rr.get("output", rr.get("error", ""))[-160:]},
        })

    # PX4 board-definition skeleton (only for the px4-fmu family)
    if any(t2["family"] == "stm32n6" for t2 in targets):
        bdir = fw / "stm32n6" / "px4" / "boards" / "px4" / "fmu-stm32n6"
        (bdir / "nuttx-config").mkdir(parents=True, exist_ok=True)
        (bdir / "default.px4board").write_text(
            '<?xml version="1.0"?>\n'
            '<px4board model="fmu-stm32n6" vendor="fluxpcb" label="FluxPCB STM32N6" '
            'image="" url="https://github.com/DataFlux-Robot/fluxpcb" '
            'schema="1.0">\n'
            '  <airflow><param default="0" name="SENS_BOARD_ROT"/></airflow>\n'
            '</px4board>\n', encoding="utf-8")
        (bdir / "bootloader.txt").write_text(
            "https://github.com/PX4/Bootloader/blob/main/px4fmu-n6/\n",
            encoding="utf-8")
        (bdir / "rc.board_defaults").write_text(
            "#!/bin/sh\n# FluxPCB fmu-stm32n6 board defaults\n"
            "param set-default SYS_BL_VERSION 0\n", encoding="utf-8")
        (bdir / "README.md").write_text(
            "# fmu-stm32n6 (FluxPCB skeleton)\n\n"
            "Board-definition skeleton auto-generated by FluxPCB.\n"
            "Integrate into a PX4-Autopilot source tree: copy this folder to\n"
            "boards/px4/fmu-stm32n6 and add the NuttX config (soc/stm32n6).\n"
            "Firmware logic (boot order / SPI loopback) is host-regression\n"
            "tested via fw_logic.c in this same tree.\n", encoding="utf-8")

    (fw / "regression.json").write_text(
        json.dumps({"targets": targets}, ensure_ascii=False, indent=1),
        encoding="utf-8")
    (fw / "build_ok.json").write_text(json.dumps({"targets": [
        {"family": t["family"], "build": t["build"], "main": t["main"]}
        for t in targets]}, ensure_ascii=False, indent=1), encoding="utf-8")
    loop_ok = bool(targets) and all(t["build"] == "ok" for t in targets)
    (fw / "spi_loopback.json").write_text(json.dumps({
        "result": "pass" if loop_ok else "fail",
        "detail": ("C代码主机执行: fw_spi_loopback memcmp==0 (regression.c)"
                   if loop_ok else "主机回归未通过/编译器缺席"),
        "targets": [t["family"] for t in targets]}, ensure_ascii=False, indent=1),
        encoding="utf-8")
    st = targets[0]["regression"]["status"] if targets else "n/a"
    notes.append(f"固件{len(targets)}个目标: ESP-IDF工程+共享源码主机回归({st})")
    return notes
