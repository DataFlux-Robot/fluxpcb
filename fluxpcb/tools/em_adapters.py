# -*- coding: utf-8 -*-
"""External-solver adapter layer (S5): openEMS / OpenFOAM / Elmer / Meep.

None of these are installed on this machine — the adapter GENERATES ready-
to-run case files (openEMS python scripts, OpenFOAM chtMultiRegionFoam case,
Meep near2far script) into the project's sim/ tree and probes availability
at gate time. Installed -> run; missing -> BLOCKED honestly (never faked).
"""
from __future__ import annotations

import shutil
from pathlib import Path


def probe() -> dict:
    out = {}
    for key, names in {
        "openems": ("openEMS",),
        "openfoam": ("foamRun", "blockMesh"),
        "elmer": ("ElmerSolver",),
        "meep": ("meep",),
        "gmsh": ("gmsh",),
    }.items():
        out[key] = any(shutil.which(n) for n in names)
    # bundled portable openEMS under tools_bin/ (CLI mode; python wheels in
    # the package need cp313+ which the host python may not match)
    root = Path(__file__).resolve().parent.parent.parent
    bundled = root / "tools_bin" / "openEMS" / "openEMS.exe"
    if not out["openems"] and bundled.exists():
        out["openems"] = True
        out["openems_path"] = str(bundled)
        out["openems_mode"] = "cli"
    try:
        import importlib.util
        out["meep_py"] = bool(importlib.util.find_spec("meep"))
        out["skrf"] = bool(importlib.util.find_spec("skrf"))
    except Exception:
        pass
    return out


