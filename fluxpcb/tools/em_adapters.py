def generate_cases(project_dir: Path) -> list[str]:
    import yaml
    spec = {}
    sf = project_dir / "spec.yaml"
    if sf.exists():
        spec = yaml.safe_load(sf.read_text(encoding="utf-8")) or {}
    d = project_dir / "sim" / "em_cases"
    d.mkdir(parents=True, exist_ok=True)
    er = (spec.get("constraints") or {}).get("er", 4.4)
    cases = []
    (d / "return_current.py").write_text(
        OPENEMS_RETURN_CURRENT.format(h_mm=0.2, w_mm=0.3, er=er), encoding="utf-8")
    cases.append("return_current.py")
    (d / "resonance_sweep.py").write_text(
        OPENEMS_RESONANCE.format(L_mm=52.0, W_mm=30.0, h_mm=1.6, er=er),
        encoding="utf-8")
    cases.append("resonance_sweep.py")
    (d / "farfield.py").write_text(OPENEMS_FARFIELD, encoding="utf-8")
    cases.append("farfield.py")
    (d / "meep_farfield.py").write_text(MEEP_NEAR2FAR, encoding="utf-8")
    cases.append("meep_farfield.py")
    (d / "README.md").write_text(
        "# EM field cases (auto-generated)\n\n"
        "Install openEMS (+CSXCAD python) or meep, then run each script "
        "from this directory. Results land in sim_*/ subfolders "
        "(J dumps in ParaView, S2P sweeps, nf2ff patterns).\n",
        encoding="utf-8")
    return cases


def generate_thermal_case(project_dir: Path) -> str:
    d = project_dir / "sim" / "thermal_case"
    (d / "constant").mkdir(parents=True, exist_ok=True)
    (d / "0.orig").mkdir(parents=True, exist_ok=True)
    (d / "system").mkdir(parents=True, exist_ok=True)
    (d / "README.md").write_text(
        "# OpenFOAM chtMultiRegionFoam case skeleton (auto-generated)\n\n"
        "solid region: board (k=0.3 W/mK, copper planes smeared 35um "
        "=> effective kx=ky~30, kz~0.3); heat sources per footprint from "
        "sim/thermal_input.yaml.\n"
        "fluid region: air enclosure, natural convection (Boussinesq).\n"
        "Run: blockMesh; topoSet; chtMultiRegionFoam (or foamRun -solver "
        "chtMultiRegionFoam in ESI v23+)\n"
        "Alternative: Elmer StatCurrentSolver+HeatSolver, see gates/thermal_cfd.\n",
        encoding="utf-8")
    return str(d.relative_to(project_dir))


def run_cases(project_dir: Path, log=print) -> list[dict]:
    """Execute the generated cases (only reached when solvers exist)."""
    import subprocess
    d = project_dir / "sim" / "em_cases"
    results = []
    for script in ("return_current.py", "resonance_sweep.py", "farfield.py"):
        if not (d / script).exists():
            continue
        p = subprocess.run(["python", str(d / script)], capture_output=True,
                           text=True, timeout=3600, cwd=str(d),
                           encoding="utf-8", errors="replace")
        results.append({"case": script,
                        "status": "ok" if p.returncode == 0 else "fail",
                        "tail": (p.stdout + p.stderr)[-160:]})
        log(f"  [em] {script}: rc={p.returncode}")
    return results
